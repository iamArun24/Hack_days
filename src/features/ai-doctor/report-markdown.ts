import type { DiagnosisReport, Finding } from '@/ai'
import type { Entry } from '@/har/types'

const SPECIALIST_LABEL: Record<string, string> = {
  performance: 'Performance',
  reliability: 'Reliability',
  security: 'Security',
  api: 'API design',
}

function requestLines(ids: readonly number[], byId: ReadonlyMap<number, Entry>): string[] {
  return ids.flatMap((id) => {
    const e = byId.get(id)
    return e ? [`- \`#${id}\` \`${e.method} ${e.status || 'failed'}\` ${e.url}`] : []
  })
}

function finding(f: Finding, n: number, byId: ReadonlyMap<number, Entry>): string[] {
  const lines = [`### ${n}. [${f.severity.toUpperCase()}] ${f.title}`, '', f.detail, '']
  if (f.impact) lines.push(`**Impact:** ${f.impact}`, '')
  if (f.fix.length) lines.push('**Fix:**', ...f.fix.map((step, i) => `${i + 1}. ${step}`), '')
  const reqs = requestLines(f.entryIds, byId)
  if (reqs.length) lines.push('**Requests:**', ...reqs, '')
  return lines
}

/** Ticket-ready Markdown (Jira, GitHub issues, Linear) with full request URLs. */
export function reportToMarkdown(
  report: DiagnosisReport,
  entries: readonly Entry[],
  fileName: string,
): string {
  const byId = new Map(entries.map((e) => [e.id, e]))
  const out: string[] = [
    `# HAR diagnosis: ${fileName}`,
    '',
    `> ${report.headline}`,
    '',
    `**Score:** ${Math.round(report.score)}/100 · ${entries.length} requests · generated by HAR Viewer AI Doctor`,
    '',
    '## Root causes',
    '',
  ]
  report.rootCauses.forEach((f, i) => out.push(...finding(f, i + 1, byId)))

  if (report.actionPlan.length) {
    out.push(
      '## Action plan',
      '',
      '| # | Action | Owner | Effort | Impact | Requests |',
      '|---|---|---|---|---|---|',
    )
    report.actionPlan.forEach((a, i) =>
      out.push(
        `| ${i + 1} | ${a.title.replace(/\|/g, '\\|')} | ${a.owner} | ${a.effort} | ${a.impact} | ${a.entryIds.map((id) => `#${id}`).join(' ')} |`,
      ),
    )
    out.push('')
  }

  if (report.openQuestions.length) {
    out.push('## Open questions', '', ...report.openQuestions.map((q) => `- [ ] ${q}`), '')
  }

  if (report.specialists.length) {
    out.push('## Specialist notes', '')
    for (const s of report.specialists) {
      out.push(`### ${SPECIALIST_LABEL[s.agent] ?? s.agent}`, '', s.summary, '')
      for (const f of s.findings) out.push(`- **${f.title}** (${f.severity}): ${f.detail}`)
      out.push('')
    }
  }
  return out.join('\n')
}
