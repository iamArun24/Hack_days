/**
 * Sparkle action with a soft pastel gradient. While `loading` it shimmers. When AI is not set up
 * yet (no key or no consent) clicking opens AI settings instead of running — the "gate".
 */
export function AiButton({
  loading,
  children,
  onClick,
  className,
  size = 'sm',
  ...props
}: Omit<ComponentProps<'button'>, 'onClick'> & {
  loading?: boolean
  onClick: () => void
  size?: 'xs' | 'sm'
}) {
  const ready = useAiReady()
  const button = (
    <button
      type="button"
      {...props}
      onClick={ready ? onClick : openAiSettings}
      disabled={loading || props.disabled}
      aria-busy={loading || undefined}
      className={cn(
        'group/ai relative inline-flex shrink-0 items-center gap-1.5 overflow-hidden rounded-full border border-primary/25 font-medium whitespace-nowrap text-primary outline-none select-none',
        'bg-[linear-gradient(110deg,color-mix(in_oklab,var(--lavender)_32%,transparent),color-mix(in_oklab,var(--peach)_26%,transparent),color-mix(in_oklab,var(--sky)_30%,transparent))]',
        'transition-[box-shadow,transform,border-color] hover:border-primary/45 hover:shadow-[var(--shadow-soft)] focus-visible:ring-2 focus-visible:ring-ring/40 active:scale-[0.97] disabled:cursor-default',
        size === 'xs' ? 'h-6 px-2 text-[11px] [&_svg]:size-3' : 'h-7 px-2.5 text-xs [&_svg]:size-3.5',
        className,
      )}
    >
      {loading && (
        <span
          aria-hidden
          className="absolute inset-0 animate-shimmer bg-[linear-gradient(100deg,transparent_30%,color-mix(in_oklab,var(--background)_70%,transparent)_50%,transparent_70%)] bg-[length:200%_100%]"
        />
      )}
      {loading ? (
        <LoaderCircle className="relative animate-spin" />
      ) : ready ? (
        <Sparkles className="relative transition-transform group-hover/ai:rotate-12" />
      ) : (
        <KeyRound className="relative" />
      )}
      <span className="relative">{children}</span>
    </button>
  )
  if (ready) return button
  return <Tooltip content="Set up AI (Groq key) first">{button}</Tooltip>
}

/** Glass frame for any AI answer: title, body, and a provenance footer with copy / regenerate / close. */
export function AiResultCard({
  title,
  icon,
  ms,
  model,
  keyIndex,
  copyText,
  onRegenerate,
  onClose,
  children,
  className,
}: {
  title: ReactNode
  icon?: ReactNode
  ms?: number
  model?: string
  keyIndex?: number
  copyText?: string | (() => string)
  onRegenerate?: () => void
  onClose?: () => void
  children: ReactNode
  className?: string
}) {
  const meta = [
    model ? `Generated by ${model}` : 'AI generated',
    keyIndex !== undefined ? `Key #${keyIndex + 1}` : null,
    ms !== undefined ? formatDuration(ms) : null,
  ].filter(Boolean)

  return (
    <section
      className={cn(
        'relative animate-rise overflow-hidden rounded-2xl border border-primary/20 shadow-[var(--shadow-soft)] glass',
        className,
      )}
    >
      <span aria-hidden className="absolute inset-x-0 top-0 h-0.5 aurora-line" />
      <header className="flex items-center gap-2 px-4 pt-3 pb-1">
        <span className="grid size-6 shrink-0 place-items-center rounded-lg bg-gradient-to-br from-lavender/70 to-peach/60 text-primary [&_svg]:size-3.5">
          {icon ?? <Sparkles />}
        </span>
        <h3 className="min-w-0 flex-1 truncate font-display text-[15px] font-semibold tracking-tight">
          {title}
        </h3>
        {copyText !== undefined && <CopyButton value={copyText} label="Copy result" />}
        {onRegenerate && (
          <Tooltip content="Regenerate">
            <Button variant="ghost" size="icon-xs" onClick={onRegenerate} aria-label="Regenerate">
              <RotateCcw />
            </Button>
          </Tooltip>
        )}
        {onClose && (
          <Tooltip content="Dismiss">
            <Button variant="ghost" size="icon-xs" onClick={onClose} aria-label="Dismiss">
              <X />
            </Button>
          </Tooltip>
        )}
      </header>
      <div className="px-4 pt-1 pb-3">{children}</div>
      <footer className="border-t border-border/60 px-4 py-1.5 text-[11px] text-subtle-foreground">
        {meta.join(' · ')} · verify before acting
      </footer>
    </section>
  )
}

/** Running placeholder: shimmering lines with a label and a cancel action. */
export function AiThinking({
  label,
  onCancel,
  className,
}: {
  label: string
  onCancel?: () => void
  className?: string
}) {
  return (
    <div
      role="status"
      className={cn('flex flex-col gap-2 rounded-2xl border border-primary/15 px-4 py-3 glass', className)}
    >
      <div className="flex items-center gap-2 text-xs text-muted-foreground">
        <Sparkles className="size-3.5 animate-pulse text-primary" />
        <span className="flex-1">{label}</span>
        {onCancel && (
          <button type="button" onClick={onCancel} className="rounded px-1 hover:text-foreground">
            Cancel
          </button>
        )}
      </div>
      {[92, 76, 84].map((w, i) => (
        <span
          key={i}
          className="h-2 animate-shimmer rounded-full bg-[linear-gradient(90deg,var(--muted),color-mix(in_oklab,var(--lavender)_35%,var(--muted)),var(--muted))] bg-[length:200%_100%]"
          style={{ width: `${w}%`, animationDelay: `${i * 120}ms` }}
        />
      ))}
    </div>
  )
}

export function AiError({
  message,
  onRetry,
  needsSetup,
  className,
}: {
  message: string
  onRetry?: () => void
  needsSetup?: boolean
  className?: string
}) {
  return (
    <div
      role="alert"
      className={cn(
        'flex items-start gap-2 rounded-2xl border border-danger/25 bg-blush/20 px-3 py-2 text-xs text-foreground',
        className,
      )}
    >
      <span className="min-w-0 flex-1 pt-0.5">{message}</span>
      {needsSetup ? (
        <Button size="xs" variant="outline" onClick={openAiSettings}>
          <KeyRound /> AI settings
        </Button>
      ) : (
        onRetry && (
          <Button size="xs" variant="outline" onClick={onRetry}>
            <RotateCcw /> Retry
          </Button>
        )
      )}
    </div>
  )
}

/** Transparency: shows exactly what text would be sent to the model (already redacted). */
export function WhatIsSent({ payload, className }: { payload: () => string; className?: string }) {
  return (
    <Collapsible.Root className={cn('group/sent text-[11px]', className)}>
      <Collapsible.Trigger className="inline-flex items-center gap-1 rounded text-subtle-foreground outline-none hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring/40">
        <Eye className="size-3" />
        What is sent
        <ChevronRight className="size-3 transition-transform group-data-[state=open]/sent:rotate-90" />
      </Collapsible.Trigger>
      <Collapsible.Content>
        <SentPreview payload={payload} />
      </Collapsible.Content>
    </Collapsible.Root>
  )
}

function SentPreview({ payload }: { payload: () => string }) {
  const text = payload() || '(nothing — AI is not set up yet)'
  return (
    <div className="relative mt-1.5">
      <pre className="max-h-56 overflow-auto rounded-xl border bg-muted/40 p-2.5 font-mono text-[10.5px] leading-relaxed break-all whitespace-pre-wrap text-muted-foreground">
        {text}
      </pre>
      <p className="mt-1 text-subtle-foreground">
        Secrets, cookies and tokens are redacted before sending · ~
        {Math.ceil(text.length / 4).toLocaleString()} tokens
      </p>
    </div>
  )
}
